import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { AgyAdapter } from "../src/adapters/agy.ts";
import { AdapterRegistry } from "../src/adapters/registry.ts";
import { openIndexDb } from "../src/sqlite.ts";
import { buildAgy, AGY_ID, field } from "./fixtures/agy.mjs";

const home = fs.mkdtempSync(path.join(os.tmpdir(), "session-hub-agy-"));
try {
  const adapter = new AgyAdapter(home);
  assert.equal((await adapter.detect()).status, "path_missing");
  assert.deepEqual(await adapter.listSessions(), []);
  assert.equal(await adapter.getSession(AGY_ID), null);
  const root = await buildAgy(home, "/srv/a project");
  const source = path.join(root, "conversations", `${AGY_ID}.db`);
  const idle = await openIndexDb(source);
  idle.get("pragma journal_mode = WAL");
  idle.close();
  const before = fs.readFileSync(source);
  const beforeFiles = fs.readdirSync(path.dirname(source)).sort();
  assert.ok(new AdapterRegistry(home).get("agy"));
  assert.equal((await adapter.detect()).sessionCount, 1);
  assert.deepEqual(await adapter.listSessions({ maxSessions: 0 }), []);
  const [row] = await adapter.listSessions();
  assert.equal(row.uid, `agy:${AGY_ID}`);
  assert.equal(row.cwd, "/srv/a project");
  assert.equal(row.createdAt, null);
  assert.equal(row.updatedAt, "2026-01-01T00:00:00.123Z");
  assert.match(row.searchText, /least recently used eviction/);
  assert.equal(row.messageCount, 2);
  const detail = await adapter.getSession(AGY_ID);
  assert.deepEqual(detail.messages.map((m) => m.role), ["user", "assistant"]);
  assert.deepEqual(detail.tools, [{ name: "bash", count: 1 }]);
  assert.deepEqual(detail.commands, ["npm test"]);
  assert.equal(detail.fidelity.hasReasoning, true);
  assert.equal(detail.fidelity.hasToolResults, false);
  assert.equal(detail.fidelity.filesChanged, null);
  assert.equal(await adapter.getSession("nonexistent"), null);
  assert.equal(await adapter.buildNativeResume("../../escape"), null);
  const resume = await adapter.buildNativeResume(AGY_ID);
  assert.equal(resume.command, "agy");
  assert.deepEqual(resume.args, ["--conversation", AGY_ID]);
  assert.equal(resume.requiresConfirmation, true);
  assert.deepEqual(fs.readFileSync(source), before, "source remains unchanged");
  assert.deepEqual(fs.readdirSync(path.dirname(source)).sort(), beforeFiles, "no WAL sidecars created for an idle database");
  const live = await openIndexDb(source);
  live.run("insert into steps values (100, 0, ?)", [field(20, field(1, "live WAL reply"))]);
  assert.ok((await adapter.getSession(AGY_ID)).messages.some((m) => m.text === "live WAL reply"), "uncheckpointed WAL content is visible");
  live.run("delete from steps where idx = 100");
  live.close();

  const db = await openIndexDb(source);
  db.run("insert into steps values (2, 0, ?)", [Buffer.from([0x9a, 1, 0xff])]); // truncated length
  db.run("insert into steps values (3, 99, ?)", [field(20, field(1, "unsupported format"))]);
  db.run("insert into steps values (4, 0, ?)", [field(99, field(1, "not prose"))]);
  db.run("insert into steps values (5, 0, ?)", [field(19, field(1, "legacy query"))]);
  db.run("insert into steps values (6, 0, ?)", [field(20, Buffer.concat([field(1, "original"), field(8, "modified response")]))]);
  db.close();
  const partial = await adapter.getSession(AGY_ID);
  assert.equal(partial.messages.length, 4);
  assert.equal(partial.messages.at(-1).text, "modified response");
  assert.ok(partial.fidelity.notes.some((n) => n.includes("3 unsupported or malformed")));
  assert.ok(!partial.searchText.includes("not prose"));

  fs.unlinkSync(source);
  const missing = await adapter.getSession(AGY_ID);
  assert.equal(missing.title, "Fake Antigravity Session");
  assert.deepEqual(missing.messages, []);
  assert.ok(missing.fidelity.notes.some((n) => n.includes("metadata only")));
  const summary = await openIndexDb(path.join(root, "conversation_summaries.db"));
  summary.run("update conversation_summaries set conversation_id = ?, workspace_uris = ?", ["../../escape", "malformed"]);
  summary.close();
  const unsafe = await adapter.getSession("../../escape");
  assert.equal(unsafe.cwd, null);
  assert.equal(unsafe.path, path.join(root, "conversation_summaries.db"));
  assert.deepEqual(unsafe.messages, []);
  const bad = await openIndexDb(path.join(root, "conversation_summaries.db"));
  bad.run("drop table conversation_summaries");
  bad.close();
  assert.equal((await adapter.detect()).status, "unsupported_version");
  await assert.rejects(() => adapter.listSessions());
  console.log("PASS agy: discovery, transcripts, search text, resume, read-only, malformed/unknown payloads, missing databases, safe paths, schema drift");
} finally { fs.rmSync(home, { recursive: true, force: true }); }
